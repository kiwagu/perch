/**
 * The contract's reference, `contract/REFERENCE.md`: every key of the contract's files with its
 * describe text, read from the schemas the engine writes, then every rule of the engine that no
 * key states, each under an anchor of its own, so a guide links to it instead of restating it.
 */

import { type ReferenceSection, referenceSections } from './keys'
import type { ReferenceRule } from './rule'
import { ruleTextOf } from './rule-text'
import { REFERENCE_RULES } from './rules'
import { referenceSlug } from './slug'

const TITLE = '# Contract reference'

const GENERATED =
  "Generated by `bun run contract:schemas` from the describe texts of the engine's schemas and its registry of rules: never edit it by hand."

const READING =
  "A key is written as its path from its file's root, `<name>` standing for any name of a map; its anchor is the file and the path in lower case (`#screen-anchors-name-secret`), and a rule's is `rule-<id>`."

const entry = (heading: string, slug: string, text: string): string =>
  `### ${heading}\n\n<a id="${slug}"></a>\n${text}`

const sectionOf = ({ file, description, keys }: ReferenceSection): string[] => [
  `## ${file.title}`,
  ...(description === undefined ? [] : [description]),
  ...keys.map((key) =>
    entry(`\`${key.path.join('.')}\``, referenceSlug(key.file, ...key.path), key.description),
  ),
]

/** A rule's entry, its text ending with a link to each key it concerns (`ruleTextOf`). */
const ruleOf = (rule: ReferenceRule): string =>
  entry(rule.title, referenceSlug('rule', rule.id), ruleTextOf(rule))

/** The text of `contract/REFERENCE.md`. */
export function renderReference(): string {
  return `${[
    `${TITLE}\n${GENERATED}`,
    READING,
    ...referenceSections().flatMap(sectionOf),
    '## Rules',
    ...REFERENCE_RULES.map(ruleOf),
  ].join('\n\n')}\n`
}
