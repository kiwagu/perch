import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { afterEach, describe, expect, it } from 'vitest'

import { type Contract, loadContract } from '../check'
import { sampleContract } from '../check/contract.fixture'
import { formatProblem, TERMS_FILE, VOCABULARY_FILE } from '../files'

import { moduleConstants, writeEmitRepository } from './emit.fixture'
import { termsModuleOf } from './terms'

const roots: string[] = []

/** The emit repository at version 6, after `change` edits its files. */
function loaded(change: (root: string) => void = () => {}): Contract {
  const root = mkdtempSync(join(tmpdir(), 'ui-contract-emit-terms-'))

  roots.push(root)
  writeEmitRepository(root, { version: 6, defaults: 80 })
  change(root)

  const { contract, problems } = loadContract(root)

  if (contract === undefined) {
    throw new Error(problems.map(formatProblem).join('\n'))
  }

  return contract
}

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true })
  }
})

describe('termsModuleOf', () => {
  it('holds every role by its name and the route of every screen bound to one, by its id', () => {
    expect(moduleConstants(termsModuleOf(loaded()))).toEqual({
      CONTRACT_ROLES: { guest: 'guest', identity: 'identity', member: 'member' },
      CONTRACT_ROUTES: { 'not-found': '/$', sample: '/sample/$key' },
      CONTRACT_INVARIANTS: {},
    })
  })
  it('holds the roles of the terms file when the contract writes one', () => {
    const contract = loaded((root) => {
      const vocabulary = join(root, VOCABULARY_FILE)

      writeFileSync(
        vocabulary,
        readFileSync(vocabulary, 'utf8').replace(/\n## Roles\n[\s\S]*?(?=\n## )/, ''),
      )
      writeFileSync(
        join(root, TERMS_FILE),
        'contexts: { sample: { meaning: The sample. } }\nterms: {}\nroles:\n  member: { meaning: A member. }\n  guest: { meaning: Nobody. }\n',
      )
    })

    expect(moduleConstants(termsModuleOf(contract))).toMatchObject({
      CONTRACT_ROLES: { guest: 'guest', member: 'member' },
    })
  })
  it("names a screen's further routes by its id and their path, so a binding added before them moves none", () => {
    const contract = sampleContract()
    const sample = contract.screens.screens[1]
    const first = sample?.bindings[0]

    if (sample === undefined || first === undefined) {
      throw new Error('the sample has no binding')
    }

    sample.bindings = [first, { ...first, path: '/thing/$key' }, { ...first, path: '/item/$key' }]

    expect(moduleConstants(termsModuleOf(contract))).toMatchObject({
      CONTRACT_ROUTES: {
        sample: '/sample/$key',
        'sample@/thing/$key': '/thing/$key',
        'sample@/item/$key': '/item/$key',
      },
    })
  })
  it('holds each invariant that states numbers: a count by its name, a duration in milliseconds under its name with Ms', () => {
    const contract = sampleContract()

    contract.screens.platform.invariants = {
      'failed-sign-ins': {
        rule: '{limit} within {window}.',
        refuses: 'rate-limited',
        values: { window: { minutes: 15 }, limit: 10 },
      },
      'credential-checks': {
        rule: '{limit} in {window}.',
        refuses: 'rate-limited',
        values: { limit: 20, window: { seconds: 10 } },
      },
      'invitation-attempts': {
        rule: '{accountLimit} and {addressLimit} in {window}.',
        refuses: 'rate-limited',
        values: { addressLimit: 60, accountLimit: 30, window: { hours: 1 } },
      },
      'last-admin': { rule: 'An organisation keeps an admin.', refuses: 'last-admin' },
    }

    expect(moduleConstants(termsModuleOf(contract))['CONTRACT_INVARIANTS']).toEqual({
      'credential-checks': { limit: 20, windowMs: 10_000 },
      'failed-sign-ins': { limit: 10, windowMs: 900_000 },
      'invitation-attempts': { accountLimit: 30, addressLimit: 60, windowMs: 3_600_000 },
    })
    expect(termsModuleOf(contract)).toContain(
      '"failed-sign-ins": {\n    "limit": 10,\n    "windowMs": 900000\n  }',
    )
  })
  it('writes the three constants as plain data under the generated header, keys sorted', () => {
    const text = termsModuleOf(loaded())

    expect(
      text,
    ).toBe(`// GENERATED by @workspace/ui-contract from the contract (ui-contract emit terms). Do not edit.

/** Every role of the contract, by its name. */
export const CONTRACT_ROLES = {
  "guest": "guest",
  "identity": "identity",
  "member": "member"
} as const

/** The route path of every binding of a screen: its first by the screen's id, which names its file; a further one by the id and its path, \`<id>@<path>\`. */
export const CONTRACT_ROUTES = {
  "not-found": "/$",
  "sample": "/sample/$key"
} as const

/** Every invariant that states numbers, by its name: each count by its name, each duration in milliseconds under its name with \`Ms\`. */
export const CONTRACT_INVARIANTS = {} as const
`)
  })
})
