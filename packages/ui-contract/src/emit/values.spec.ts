import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { afterEach, describe, expect, it } from 'vitest'
import { parse } from 'yaml'

import { type Contract, loadContract } from '../check'
import { formatProblem, MODEL_FILE, PLATFORM_FILE } from '../files'

import { type EmitRepository, moduleData, writeEmitRepository } from './emit.fixture'
import { valuesModuleOf } from './values'

const roots: string[] = []

/** The contract of the sample at `options`, loaded as every reader takes it. */
function loaded(options: EmitRepository): { root: string; contract: Contract } {
  const root = mkdtempSync(join(tmpdir(), 'ui-contract-emit-values-'))

  roots.push(root)
  writeEmitRepository(root, options)

  const { contract, problems } = loadContract(root)

  if (contract === undefined) {
    throw new Error(problems.map(formatProblem).join('\n'))
  }

  return { root, contract }
}

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true })
  }
})

type Values = Record<string, Record<string, unknown>>

const valuesOf = (contract: Contract): Values => moduleData(valuesModuleOf(contract)) as Values

type Written = Record<string, Record<string, unknown>>

/** What the platform file writes of the value `name`, as written. */
const writtenValue = (root: string, name: string): Record<string, unknown> | undefined =>
  (parse(readFileSync(join(root, PLATFORM_FILE), 'utf8')) as { values: Written }).values[name]

/** What the model file writes of the thing's field `name`, as written. */
const writtenField = (root: string, name: string): Record<string, unknown> | undefined =>
  (
    JSON.parse(readFileSync(join(root, MODEL_FILE), 'utf8')) as {
      $defs: { thing: { properties: Written } }
    }
  ).$defs.thing.properties[name]

const SIX = { version: 6, defaults: 80 } as const

describe('valuesModuleOf', () => {
  it('holds every value of the platform and every field of the model, by name', () => {
    const { contract } = loaded(SIX)

    expect(Object.keys(valuesOf(contract))).toEqual([
      'email',
      'name',
      'password',
      'thing.author',
      'thing.created_at',
      'thing.email',
      'thing.id',
      'thing.size',
      'thing.title',
    ])
  })

  it('gives a value and a field that name no limit the default length, as they resolve', () => {
    const { root, contract } = loaded(SIX)
    const values = valuesOf(contract)

    expect(writtenValue(root, 'name')).not.toHaveProperty('maxLength')
    expect(writtenField(root, 'title')).not.toHaveProperty('maxLength')
    expect(values['name']).toEqual({ type: 'string', minLength: 1, maxLength: 80 })
    expect(values['thing.title']).toEqual({ type: 'string', minLength: 1, maxLength: 80 })
  })

  it('keeps a written limit, and gives a value that writes maxLength: null no limit', () => {
    const { root, contract } = loaded(SIX)
    const values = valuesOf(contract)

    expect(writtenValue(root, 'password')).toHaveProperty('maxLength', null)
    expect(values['password']).toEqual({ type: 'string', minLength: 1 })
    expect(values['email']).toEqual({ type: 'string', maxLength: 254, format: 'email' })
  })

  it('says a field of the model is read-only, and takes no default on it or on an enum', () => {
    const values = valuesOf(loaded(SIX).contract)

    expect(values['thing.email']).toEqual({
      type: 'string',
      maxLength: 254,
      format: 'email',
      readOnly: true,
    })
    expect(values['thing.id']).toEqual({ type: 'string', readOnly: true })
    expect(values['thing.size']).toEqual({ enum: ['small', 'large'] })
  })

  it('gives no default length before version 6, a written default included', () => {
    for (const options of [{ version: 5 }, { version: 5, defaults: 80 }]) {
      const values = valuesOf(loaded(options).contract)

      expect(values['name']).toEqual({ type: 'string', minLength: 1 })
      expect(values['thing.title']).toEqual({ type: 'string', minLength: 1 })
      expect(values['password']).toEqual({ type: 'string', minLength: 1 })
    }
  })

  it('writes plain data under a GENERATED header, its keys sorted, the same text every time', () => {
    const { root, contract } = loaded(SIX)
    const text = valuesModuleOf(contract)
    const again = loadContract(root).contract ?? expect.unreachable('the contract loads again')

    expect(text.split('\n')[0]).toMatch(
      /^\/\/ GENERATED by @workspace\/ui-contract .*Do not edit\.$/,
    )
    expect(text).toContain('\nexport const CONTRACT_VALUES = {\n')
    expect(text.endsWith('\n} as const\n')).toBe(true)
    expect(text).not.toMatch(/^import /m)
    expect(valuesModuleOf(again)).toBe(text)

    const keys = Object.keys(valuesOf(contract))

    expect(keys).toEqual([...keys].sort())
  })
})
