/**
 * The text of a module the engine emits for a layer below the contract: plain data and nothing
 * else, `export const <NAME> = <JSON> as const` under a GENERATED header, no import and no
 * function. Its keys are sorted by their UTF-16 code units, never by a locale, and its JSON is two
 * spaces deep, one key per line, so the same contract writes the same bytes on every machine and a
 * changed limit is a one-line diff.
 */

export interface EmittedModule {
  /** The constant's name, `CONTRACT_VALUES`. */
  readonly name: string
  /** The argument of `ui-contract emit` that writes it, `values`. */
  readonly command: string
  /** What the constant holds, one sentence for its doc comment. */
  readonly holds: string
  /** Its entries, in any order. */
  readonly entries: ReadonlyArray<readonly [string, unknown]>
}

const byKey = ([a]: readonly [string, unknown], [b]: readonly [string, unknown]): number =>
  a < b ? -1 : a > b ? 1 : 0

export function moduleText({ name, command, holds, entries }: EmittedModule): string {
  const data = Object.fromEntries([...entries].sort(byKey))

  return [
    `// GENERATED by @workspace/ui-contract from the contract (ui-contract emit ${command}). Do not edit.`,
    '',
    `/** ${holds} */`,
    `export const ${name} = ${JSON.stringify(data, null, 2)} as const`,
    '',
  ].join('\n')
}
