/**
 * The text of a module the engine emits for a layer below the contract: plain data and nothing
 * else, one `export const <NAME> = <JSON> as const` per constant under a GENERATED header, no
 * import and no function. Its keys are sorted by their UTF-16 code units, never by a locale, and
 * its JSON is two spaces deep, one key per line, so the same contract writes the same bytes on
 * every machine and a changed limit is a one-line diff.
 */

/** One constant of an emitted module. */
export interface EmittedConstant {
  /** The constant's name, `CONTRACT_VALUES`. */
  readonly name: string
  /** What the constant holds, one sentence for its doc comment. */
  readonly holds: string
  /** Its entries, in any order. */
  readonly entries: ReadonlyArray<readonly [string, unknown]>
}

/** A module of one constant. */
export interface EmittedModule extends EmittedConstant {
  /** The argument of `ui-contract emit` that writes it, `values`. */
  readonly command: string
}

const byKey = ([a]: readonly [string, unknown], [b]: readonly [string, unknown]): number =>
  a < b ? -1 : a > b ? 1 : 0

/** The text of a module of several constants, in the order given, each under its doc comment. */
export function constantsText(command: string, constants: readonly EmittedConstant[]): string {
  return [
    `// GENERATED by @workspace/ui-contract from the contract (ui-contract emit ${command}). Do not edit.`,
    ...constants.flatMap(({ name, holds, entries }) => [
      '',
      `/** ${holds} */`,
      `export const ${name} = ${JSON.stringify(Object.fromEntries([...entries].sort(byKey)), null, 2)} as const`,
    ]),
    '',
  ].join('\n')
}

export function moduleText({ command, ...constant }: EmittedModule): string {
  return constantsText(command, [constant])
}
