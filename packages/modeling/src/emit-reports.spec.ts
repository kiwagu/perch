import { describe, expect, it } from 'vitest'

import type { CommandFile, ShapeFile } from './collect'
import { emitPagesModel, emitSurrealkitSuites } from './emit-reports'
import { parseShape } from './shape-dialect'

const place = {
  name: 'profile',
  module: 'user',
  moduleDir: 'features/user',
  componentDir: 'features/user/pages/profile',
}
const body = 'SELECT id, name FROM profile WHERE identity = $identity AND name != $name;'

const shape: ShapeFile = {
  ...place,
  path: 'features/user/pages/profile/profile.shape.surql',
  id: 'user.profile',
  header: {
    kind: 'shape',
    params: [
      { name: 'identity', type: 'record<identity>' },
      { name: 'name', type: 'string' },
    ],
    server: false,
  },
  body,
  ast: parseShape(body),
  tables: ['profile'],
  region: 'private',
  resultType: 'Array<{ id: ProfileId; name: string }>',
}

const commands: CommandFile = {
  ...place,
  path: 'features/user/pages/profile/profile.commands.surql',
  id: 'user.profile',
  commands: [
    {
      id: 'user.profile.updateName',
      name: 'updateName',
      header: {
        kind: 'command',
        name: 'updateName',
        params: [{ name: 'id', type: 'record<profile>' }],
        allow: ['record'],
        deny: ['guest'],
      },
      body: 'UPDATE $id SET name = $name;',
      tables: ['profile'],
      region: 'private',
      ops: [{ op: 'set', record: 'id', field: 'name', value: { param: 'name' } }],
    },
  ],
}

describe('emitPagesModel', () => {
  it('describes modules with their shapes, tables, fields and commands', () => {
    expect(JSON.parse(emitPagesModel([shape], [commands]))).toEqual({
      modules: [
        {
          id: 'user',
          dir: 'features/user',
          shapes: [
            {
              id: 'user.profile',
              file: shape.path,
              tables: ['profile'],
              region: 'private',
              fields: ['id', 'name'],
            },
          ],
          commands: [
            {
              id: 'user.profile.updateName',
              file: commands.path,
              tables: ['profile'],
              region: 'private',
              ops: ['set'],
              allow: ['record'],
              deny: ['guest'],
            },
          ],
        },
      ],
    })
  })
})

const notesBody = 'SELECT id, text FROM note;'

const notes: ShapeFile = {
  ...shape,
  name: 'notes',
  componentDir: 'features/user/pages/notes',
  path: 'features/user/pages/notes/notes.shape.surql',
  id: 'user.notes',
  header: { kind: 'shape', params: [], server: false },
  body: notesBody,
  ast: parseShape(notesBody),
  tables: ['note'],
  region: 'tenant',
  resultType: 'Array<{ id: NoteId; text: string }>',
}

describe('emitSurrealkitSuites', () => {
  it('checks that a signed-in user may run every shape of a module', () => {
    expect(emitSurrealkitSuites([shape], 'identity')).toEqual([
      {
        path: 'generated-user.toml',
        toml: [
          '# GENERATED by @workspace/modeling from the shapes of module user. Do not edit.',
          '# Commands of replicated tables run as replica operations on the client, so the server',
          '# never executes them as SurrealQL and they have no permission cases here.',
          '',
          'name = "generated-user"',
          'tags = ["generated", "user"]',
          '',
          '[[cases]]',
          'name = "a signed-in user can run the shape user.profile"',
          'kind = "sql_expect"',
          'actor = "record"',
          `sql = "LET $identity = $auth.id; LET $name = 'sample'; ${body}"`,
          'allow = true',
          '',
        ].join('\n'),
      },
    ])
  })

  it('leaves out the shapes of the tenant region, and says so', () => {
    expect(emitSurrealkitSuites([shape, notes], 'identity')).toEqual([
      {
        path: 'generated-user.toml',
        toml: [
          '# GENERATED by @workspace/modeling from the shapes of module user. Do not edit.',
          '# Commands of replicated tables run as replica operations on the client, so the server',
          '# never executes them as SurrealQL and they have no permission cases here.',
          '# Shapes of the tenant region have no record access on the server yet and are not checked here.',
          '',
          'name = "generated-user"',
          'tags = ["generated", "user"]',
          '',
          '[[cases]]',
          'name = "a signed-in user can run the shape user.profile"',
          'kind = "sql_expect"',
          'actor = "record"',
          `sql = "LET $identity = $auth.id; LET $name = 'sample'; ${body}"`,
          'allow = true',
          '',
        ].join('\n'),
      },
    ])
  })

  it('writes no suite for a module whose shapes are all in the tenant region', () => {
    const board: ShapeFile = {
      ...notes,
      module: 'board',
      moduleDir: 'features/board',
      componentDir: 'features/board/pages/notes',
      path: 'features/board/pages/notes/notes.shape.surql',
      id: 'board.notes',
    }

    expect(emitSurrealkitSuites([board], 'identity')).toEqual([])
    expect(emitSurrealkitSuites([shape, board], 'identity').map(({ path }) => path)).toEqual([
      'generated-user.toml',
    ])
  })
})
