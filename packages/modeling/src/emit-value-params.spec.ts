import { describe, expect, it } from 'vitest'

import { emitValueParams, valueParamName } from './emit-value-params'
import { loadSchemaModel } from './schema-structure'

/** The shapes of the contract's resolved values: a limit, none, an enum, a read-only field. */
const values = {
  'profile.name': { type: 'string', minLength: 1, maxLength: 80 },
  'account-search': { type: 'string', maxLength: 254 },
  email: { type: 'string', maxLength: 254, format: 'email' },
  password: { type: 'string', minLength: 1 },
  role: { enum: ['member', 'admin'] },
  'profile.id': { type: 'string', readOnly: true },
  'note.text': { type: 'string', minLength: 1, maxLength: 500 },
} as const

const HEADER = [
  "-- GENERATED by @workspace/modeling from the contract's values (CONTRACT_VALUES of @workspace/kernel). Do not edit.",
  "-- One parameter for each value that has a length limit, named `<value>_max_length`: the value's name with `-` and `.` as `_`.",
  '-- The asserts of the schema name them, so a limit is written once, in the contract.',
]

describe('emitValueParams', () => {
  it('writes one parameter for each value with a length limit, by name', () => {
    expect(emitValueParams(values)._unsafeUnwrap()).toBe(
      [
        ...HEADER,
        '',
        'DEFINE PARAM OVERWRITE $account_search_max_length VALUE 254;',
        'DEFINE PARAM OVERWRITE $email_max_length VALUE 254;',
        'DEFINE PARAM OVERWRITE $note_text_max_length VALUE 500;',
        'DEFINE PARAM OVERWRITE $profile_name_max_length VALUE 80;',
        '',
      ].join('\n'),
    )
  })

  it('writes the same text whatever the order the values come in', () => {
    const reversed = Object.fromEntries(Object.entries(values).reverse())

    expect(emitValueParams(reversed)._unsafeUnwrap()).toBe(emitValueParams(values)._unsafeUnwrap())
  })

  it('writes the header alone for values without a limit', () => {
    expect(emitValueParams({ password: values.password, role: values.role })._unsafeUnwrap()).toBe(
      [...HEADER, ''].join('\n'),
    )
  })

  it('refuses two limited values that name the same parameter, naming both', () => {
    expect(
      emitValueParams({
        'profile.name': { maxLength: 80 },
        'profile-name': { maxLength: 60 },
        'note.text': { maxLength: 500 },
      })._unsafeUnwrapErr(),
    ).toEqual([
      'the values profile-name and profile.name name the same database parameter $profile_name_max_length',
    ])
  })

  it('reports every collision at once', () => {
    expect(
      emitValueParams({
        'a.b': { maxLength: 1 },
        'a-b': { maxLength: 2 },
        'c.d': { maxLength: 3 },
        'c-d': { maxLength: 4 },
        c_d: { maxLength: 5 },
      })._unsafeUnwrapErr(),
    ).toEqual([
      'the values a-b and a.b name the same database parameter $a_b_max_length',
      'the values c-d, c.d and c_d name the same database parameter $c_d_max_length',
    ])
  })

  it('lets a name collide with a value that has no limit, which gets no parameter', () => {
    expect(
      emitValueParams({
        'profile.name': { maxLength: 80 },
        'profile-name': { type: 'string' },
      }).isOk(),
    ).toBe(true)
  })

  it('writes a file the database accepts, each parameter holding its number', async () => {
    const { params, problems } = (
      await loadSchemaModel(emitValueParams(values)._unsafeUnwrap())
    )._unsafeUnwrap()

    expect(problems).toEqual([])
    expect(params).toEqual({
      account_search_max_length: '254',
      email_max_length: '254',
      note_text_max_length: '500',
      profile_name_max_length: '80',
    })
  })
})

describe('valueParamName', () => {
  it('names the parameter of a value, a `-` or a `.` of its name as `_`', () => {
    expect(valueParamName('account-search')).toBe('account_search_max_length')
    expect(valueParamName('profile.name')).toBe('profile_name_max_length')
    expect(valueParamName('email')).toBe('email_max_length')
  })

  it('names the parameters of the values emitValueParams writes one for', async () => {
    const { params } = (
      await loadSchemaModel(emitValueParams(values)._unsafeUnwrap())
    )._unsafeUnwrap()

    expect(Object.keys(params).sort()).toEqual(
      ['account-search', 'email', 'note.text', 'profile.name'].map(valueParamName).sort(),
    )
  })
})
