/**
 * The database's side of the contract's length limits: one SurrealDB parameter for each value that
 * has a `maxLength`, named `<value>_max_length` (a `-` or `.` of the value's name becomes `_`), so
 * an assert names the limit (`string::len($value) <= $profile_name_max_length`) instead of writing
 * the number again. A parameter is read when a record is written, so a new number reaches every
 * field that names it once the file is applied again (`DEFINE PARAM OVERWRITE`).
 *
 * Every value with a limit gets a parameter, whether or not a column holds it: the contract does
 * not say which values the database stores, and an unused parameter costs a line.
 */

import { err, ok, type Result } from 'neverthrow'

const HEADER = [
  "-- GENERATED by @workspace/modeling from the contract's values (CONTRACT_VALUES of @workspace/kernel). Do not edit.",
  "-- One parameter for each value that has a length limit, named `<value>_max_length`: the value's name with `-` and `.` as `_`.",
  '-- The asserts of the schema name them, so a limit is written once, in the contract.',
]

/** The database parameter that holds the length limit of the value `value` names. */
export const valueParamName = (value: string): string => `${value.replace(/[-.]/g, '_')}_max_length`

const maxLengthOf = (value: object): number | undefined =>
  'maxLength' in value && typeof value.maxLength === 'number' ? value.maxLength : undefined

const listed = (names: readonly string[]): string =>
  names.length < 2
    ? names.join('')
    : `${names.slice(0, -1).join(', ')} and ${names[names.length - 1]}`

/**
 * The text of `database/schema/common/contract-values.gen.surql` for the contract's values
 * (`CONTRACT_VALUES`, by the value's name): one `DEFINE PARAM` for each value with a numeric
 * `maxLength`, in the order of the parameter names. The problems are the parameters two limited
 * values would both define, each named with its values: a database holds one of each name.
 */
export function emitValueParams(
  values: Readonly<Record<string, object>>,
): Result<string, string[]> {
  const byParam = new Map<string, { readonly limit: number; readonly values: string[] }>()

  for (const [value, keywords] of Object.entries(values)) {
    const limit = maxLengthOf(keywords)

    if (limit !== undefined) {
      const param = valueParamName(value)

      byParam.set(param, { limit, values: [...(byParam.get(param)?.values ?? []), value] })
    }
  }

  const params = [...byParam.entries()].sort(([left], [right]) => (left < right ? -1 : 1))
  const problems = params.flatMap(([param, { values: named }]) =>
    named.length > 1
      ? [`the values ${listed(named.sort())} name the same database parameter $${param}`]
      : [],
  )

  if (problems.length > 0) {
    return err(problems)
  }

  const statements = params.map(
    ([param, { limit }]) => `DEFINE PARAM OVERWRITE $${param} VALUE ${limit};`,
  )

  return ok(`${[...HEADER, ...(statements.length > 0 ? ['', ...statements] : [])].join('\n')}\n`)
}
