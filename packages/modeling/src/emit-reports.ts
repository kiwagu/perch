/**
 * Generated reports beside the code: the page model (modules, shapes, commands
 * and the tables they touch) and per-module SurrealKit suites that check a
 * signed-in user may run every shape against the server's permissions.
 */

import type { ParamDecl } from '@workspace/data'
import { recordTableOf } from '@workspace/data'

import type { CommandFile, ShapeFile } from './collect'
import { parseTypeString } from './type-string'

export function emitPagesModel(
  shapes: readonly ShapeFile[],
  commands: readonly CommandFile[],
): string {
  const modules = new Map<
    string,
    { id: string; dir: string; shapes: unknown[]; commands: unknown[] }
  >()
  const entry = (file: { module: string; moduleDir: string }) => {
    const existing = modules.get(file.module)

    if (existing) {
      return existing
    }

    const created = {
      id: file.module,
      dir: file.moduleDir,
      shapes: [] as unknown[],
      commands: [] as unknown[],
    }

    modules.set(file.module, created)

    return created
  }

  for (const shape of shapes) {
    entry(shape).shapes.push({
      id: shape.id,
      file: shape.path,
      tables: shape.tables,
      region: shape.region,
      fields: shape.ast.projections.map((projection) => projection.name),
    })
  }

  for (const file of commands) {
    for (const command of file.commands) {
      entry(file).commands.push({
        id: command.id,
        file: file.path,
        tables: command.tables,
        region: command.region,
        ops: command.ops.map((op) => op.op),
        allow: command.header.allow,
        deny: command.header.deny,
      })
    }
  }

  const sorted = [...modules.values()].sort((left, right) => (left.id < right.id ? -1 : 1))

  return `${JSON.stringify({ modules: sorted }, null, 2)}\n`
}

/** A sample value for a parameter, as SurrealQL, for a signed-in user of the access table. */
function sampleValue(param: ParamDecl, accessTable: string): string {
  const type = parseTypeString(param.type)

  if (type.kind === 'option') {
    return 'NONE'
  }

  const table = recordTableOf(param.type)

  if (table) {
    return table === accessTable ? '$auth.id' : `(SELECT VALUE id FROM ${table} LIMIT 1)[0]`
  }

  if (type.kind === 'scalar') {
    return (
      { int: '0', float: '0', number: '0', bool: 'false', datetime: 'time::now()' }[
        type.name as string
      ] ?? "'sample'"
    )
  }

  return 'NONE'
}

const tomlString = (value: string): string => JSON.stringify(value)

export function emitSurrealkitSuites(
  shapes: readonly ShapeFile[],
  accessTable: string,
): Array<{ path: string; toml: string }> {
  const byModule = new Map<string, ShapeFile[]>()

  for (const shape of shapes) {
    byModule.set(shape.module, [...(byModule.get(shape.module) ?? []), shape])
  }

  return [...byModule.entries()]
    .sort(([left], [right]) => (left < right ? -1 : 1))
    .map(([module, moduleShapes]) => {
      const checked = moduleShapes.filter((shape) => shape.region !== 'tenant')
      const cases = checked.flatMap((shape) => {
        const bindings = shape.header.params.map(
          (param) => `LET $${param.name} = ${sampleValue(param, accessTable)};`,
        )
        const sql = [...bindings, shape.body.trim()].join(' ')

        return [
          '[[cases]]',
          `name = ${tomlString(`a signed-in user can run the shape ${shape.id}`)}`,
          'kind = "sql_expect"',
          'actor = "record"',
          `sql = ${tomlString(sql)}`,
          'allow = true',
          '',
        ]
      })

      return {
        path: `generated-${module}.toml`,
        toml: [
          `# GENERATED by @workspace/modeling from the shapes of module ${module}. Do not edit.`,
          '# Commands of replicated tables run as replica operations on the client, so the server',
          '# never executes them as SurrealQL and they have no permission cases here.',
          ...(checked.length < moduleShapes.length
            ? [
                '# Shapes of the tenant region have no record access on the server yet and are not checked here.',
              ]
            : []),
          '',
          `name = ${tomlString(`generated-${module}`)}`,
          `tags = ["generated", ${tomlString(module)}]`,
          '',
          ...cases,
        ].join('\n'),
      }
    })
}
